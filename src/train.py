def _flatten(seqs: list[list[int]]) -> tuple[np.ndarray, np.ndarray]:
    lens = np.fromiter((len(s) for s in seqs), dtype=np.int32, count=len(seqs))
    flat = np.fromiter((t for s in seqs for t in s), dtype=np.uint32)
    return flat, lens


def save_rollout_ids(out_dir: Path, r_idx: int, rb, *, seed: int,
                     backend: str) -> dict:
    """Write the exact token ids this rollout was scored on, plus a digest.

    Why: vLLM's sampler does not reproduce across processes (D-16), so a run's
    numbers cannot be regenerated by re-sampling. They *can* be re-derived from
    this file -- that is the difference between "the sampling is stochastic" and
    "the result cannot be audited". It is also the only way the L1 determinism
    probe can compare two runs bit for bit.

    Layout: `rollouts/r{idx:03d}.npz` holds ragged ids as flat uint32 + lengths.
    `rollouts/index.jsonl` gets one line per rollout with the digest, so a
    resumed run that sampled different data on the same index is visible rather
    than silently overwriting the original.
    """
    out_dir.mkdir(parents=True, exist_ok=True)
    p_flat, p_len = _flatten(rb.prompt_ids)
    c_flat, c_len = _flatten(rb.completion_ids)
    h = hashlib.sha256()
    for arr in (p_flat.astype("<u4"), p_len.astype("<i4"),
                c_flat.astype("<u4"), c_len.astype("<i4")):
        h.update(arr.tobytes())
    digest = h.hexdigest()

    base = out_dir / f"r{r_idx:03d}"
    path = base.with_suffix(".npz")
    variant = 0
    if path.exists():
        variant = 1
        while (base.parent / f"{base.name}_v{variant}.npz").exists():
            variant += 1
        path = base.parent / f"{base.name}_v{variant}.npz"

    np.savez_compressed(path, prompt_flat=p_flat, prompt_len=p_len,
                        completion_flat=c_flat, completion_len=c_len)
    rec = {
        "rollout_idx": r_idx,
        "seed": seed,
        "backend": backend,
        "n_responses": int(len(c_len)),
        "prompt_tokens": int(p_len.sum()),
        "completion_tokens": int(c_len.sum()),
        "max_seq_len": int((p_len + c_len).max()) if len(c_len) else 0,
        "sha256": digest,
        "npz": path.name,
        "variant": variant,
        "bytes": path.stat().st_size,
    }
    with open(out_dir / "index.jsonl", "a", encoding="utf-8") as f:
        f.write(json.dumps(rec) + "\n")
    return rec


def _sha256_file(path: Path, chunk: int = 1 << 22) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(chunk), b""):
            h.update(block)
    return h.hexdigest()


def snapshot_adapter(run_dir: Path, r_idx: int, adapter_dir: str | Path,
                     min_free_gb: float = 4.0) -> dict:
    """Copy the LoRA weights that produced rollout r_idx into the run directory.

    Why: `state.pt` and `runs/_adapter` are both overwritten, so after a run the
    only surviving weights are the last ones. Any question of the form "what did
    the policy look like when this rollout's ratio was 1.31" needs the weights
    for that rollout, and they cannot be reconstructed from token ids alone.

    Cost: 266 MiB per rollout in fp32 (the trained LoRA is 69.7 M params and PEFT
    writes float32, which is the dtype the optimizer holds -- casting to bf16
    would make the snapshot NOT the value that was trained). Eight snapshots per
    run is 2.1 GiB, hence the free-space guard: a full disk would kill a
    16-hour campaign, and a missing snapshot is recoverable, a dead run is not.
    """
    src = Path(adapter_dir)
    out_dir = run_dir / "adapters"
    out_dir.mkdir(parents=True, exist_ok=True)
    dst = out_dir / f"r{r_idx:03d}"
    rec = {"rollout_idx": r_idx, "src": str(src), "dst": dst.name, "skipped": False}

    if not src.exists():
        rec.update(skipped=True, reason=f"no adapter at {src}")
    else:
        free_gb = shutil.disk_usage(out_dir).free / 2**30
        need_gb = sum(p.stat().st_size for p in src.rglob("*") if p.is_file()) / 2**30
        if free_gb < max(min_free_gb, need_gb * 1.5):
            rec.update(skipped=True, reason=f"free {free_gb:.1f} GiB < needed {need_gb:.1f} GiB")
        else:
            variant = 0
            while dst.exists():
                variant += 1
                dst = out_dir / f"r{r_idx:03d}_v{variant}"
            tmp = out_dir / (dst.name + ".tmp")
            if tmp.exists():
                shutil.rmtree(tmp)
            shutil.copytree(src, tmp)
            tmp.replace(dst)
            rec["dst"] = dst.name
            files = {p.name: p.stat().st_size for p in dst.rglob("*") if p.is_file()}
            st = sorted(dst.glob("*.safetensors"))
            rec.update(bytes=sum(files.values()), files=files,
                       variant=variant,
                       sha256=_sha256_file(st[0]) if st else "",
                       meta=json.loads((dst / "AUDIT_ADAPTER_META.json").read_text())
                       if (dst / "AUDIT_ADAPTER_META.json").exists() else {})

    if rec["skipped"]:
        print(f"[adapter] rollout {r_idx} NOT archived: {rec['reason']}")
    with open(out_dir / "index.jsonl", "a", encoding="utf-8") as f:
        f.write(json.dumps(rec, ensure_ascii=False) + "\n")
    return rec


def _rescale(buf, scale: float) -> None:
    for b in buf:
        b.mul_(scale)


def _add_into(dst, src, scale: float) -> None:
    for d, s in zip(dst, src):
        d.add_(s, alpha=scale)


def _grad_norm(params_or_tensors) -> float:
    """L2 norm of parameter gradients (or of raw tensors).

    Accepts Parameters and reads `.grad`, because passing the parameters
    themselves computes ||theta|| instead of ||grad|| -- a mistake that is
    invisible on a real run (it produces a plausible-looking number) and only
    shows up as a sigma of zero. Accumulated in float64: the variance formula
    behind sigma is a difference of two large numbers, and a float32 sum can
    flip its sign.
    """
    total = 0.0
    for t in params_or_tensors:
        g = t.grad if isinstance(t, torch.nn.Parameter) else t
        if g is None:
            continue
        total += float(g.detach().float().pow(2).sum(dtype=torch.float64))
    return total ** 0.5


def _lr_at(step: int, total: int, base_lr: float, warmup_ratio: float) -> float:
    warm = max(1, int(total * warmup_ratio))
    if step < warm:
        return base_lr * (step + 1) / warm
    prog = (step - warm) / max(1, total - warm)
    return base_lr * 0.5 * (1.0 + np.cos(np.pi * min(1.0, prog)))


def _sh(*args: str) -> str:
    """Run a short command and return stdout, or "" on any failure.

    Provenance is worth having but never worth killing a 16-hour run over, so
    every failure mode (binary missing, not a git repo, timeout) degrades to "".
    """
    try:
        p = subprocess.run(args, capture_output=True, text=True, timeout=5)
        return p.stdout.strip() if p.returncode == 0 else ""
    except Exception:
        return ""


def _pkg_version(name: str) -> str:
    try:
        from importlib.metadata import version

        return version(name)
    except Exception:
        return ""


def _commit_from_file() -> str:
    """The rented box has no .git (code arrives by scp), so the commit is also
    dropped into a plain `COMMIT` file next to README.md."""
    for name in ("COMMIT", "COMMIT.txt"):
        p = Path(__file__).resolve().parents[1] / name
        if p.exists():
            lines = p.read_text(encoding="utf-8").strip().splitlines()
            return lines[0][:40] if lines else ""
    return ""


def _run_meta(cfg) -> dict:
    import transformers

    # Provenance rule (D-23): the code on the rented box arrives by scp, so a
    # stale .git there can name a commit that is NOT what ran. The stamped
    # COMMIT file is the authority when the two disagree; both are recorded so
    # the disagreement stays visible instead of being resolved silently.
    commit_file = _commit_from_file()
    git_head = _sh("git", "rev-parse", "HEAD")
    if commit_file and commit_file != git_head:
        commit, source = commit_file, "file"
    elif git_head:
        commit, source = git_head, "git"
    else:
        commit, source = commit_file, ("file" if commit_file else "")
    dirty = bool(_sh("git", "status", "--porcelain")) if git_head else None
    meta = {
        "created": time.strftime("%Y-%m-%dT%H:%M:%S%z"),
        "host": platform.node(),
        "platform": platform.platform(),
        "python": sys.version.split()[0],
        "torch": torch.__version__,
        "transformers": transformers.__version__,
        "cuda": torch.version.cuda,
        "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else "cpu",
        # D-21: the code that produced this run, and the sampler library that
        # produced its data. Both were missing, so a run could not be traced
        # back to a commit without reading the shell history.
        "vllm": _pkg_version("vllm"),
        "numpy": np.__version__,
        "nvidia_driver": _sh("nvidia-smi", "--query-gpu=driver_version", "--format=csv,noheader"),
        "git_commit": commit,
        "git_commit_source": source,
        "git_head_in_checkout": git_head,
        "git_dirty": dirty,
        "argv": sys.argv,
        "cwd": os.getcwd(),
    }
    if torch.cuda.is_available():
        meta["gpu_total_gb"] = round(torch.cuda.get_device_properties(0).total_memory / 1e9, 2)
    return meta


